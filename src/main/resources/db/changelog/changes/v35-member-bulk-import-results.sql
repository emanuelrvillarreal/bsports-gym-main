CREATE TABLE `member_bulk_import_results` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `uuid` CHAR(36) NOT NULL UNIQUE,
  `status` TINYINT DEFAULT 0,
  `company_id` BIGINT NOT NULL,
  `import_id` VARCHAR(36) NOT NULL UNIQUE,
  `total_rows` INT NOT NULL,
  `success_count` INT NOT NULL,
  `error_count` INT NOT NULL,
  `warning_count` INT NOT NULL,
  `import_status` VARCHAR(20) NOT NULL,
  `error_message` VARCHAR(500),
  `rows_data` LONGTEXT,
  `id_user_created` BIGINT,
  `id_user_updated` BIGINT,
  `id_user_deleted` BIGINT,
  `date_created` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  `date_updated` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `date_deleted` TIMESTAMP NULL,
  PRIMARY KEY (`id`),
  FOREIGN KEY (`company_id`) REFERENCES `companies`(`id`),
  INDEX `idx_import_id` (`import_id`),
  INDEX `idx_company_date` (`company_id`, `date_created`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
