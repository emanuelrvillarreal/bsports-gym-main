CREATE TABLE cuotas (
  id BIGINT NOT NULL AUTO_INCREMENT,
  status TINYINT NOT NULL DEFAULT 0,
  uuid CHAR(36) NOT NULL,
  id_user_created BIGINT NULL,
  id_user_updated BIGINT NULL,
  id_user_deleted BIGINT NULL,
  date_created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  date_updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  date_deleted TIMESTAMP NULL,
  company_id BIGINT NOT NULL,
  persona_id BIGINT NOT NULL,
  titular_id BIGINT NOT NULL,
  tipo VARCHAR(20) NOT NULL,
  actividad_id BIGINT NULL,
  mes INT NULL,
  anio INT NULL,
  monto DECIMAL(12, 2) NOT NULL,
  vencimiento DATE NOT NULL,
  estado VARCHAR(20) NOT NULL,
  concepto VARCHAR(255) NOT NULL,
  origen VARCHAR(20) NOT NULL,
  anulada_por BIGINT NULL,
  anulada_motivo VARCHAR(512) NULL,
  anulada_at TIMESTAMP NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_cuotas_uuid (uuid),
  UNIQUE KEY uk_cuotas_social_ciclo (company_id, persona_id, mes, anio, tipo),
  UNIQUE KEY uk_cuotas_actividad_ciclo (company_id, persona_id, actividad_id, mes, anio),
  KEY fk_cuotas_company (company_id),
  KEY idx_cuotas_titular_estado (company_id, titular_id, estado),
  KEY idx_cuotas_persona_estado (company_id, persona_id, estado),
  KEY idx_cuotas_vencimiento (company_id, vencimiento),
  KEY fk_cuotas_anulada_por (anulada_por),
  CONSTRAINT fk_cuotas_company FOREIGN KEY (company_id) REFERENCES companies (id),
  CONSTRAINT fk_cuotas_anulada_por FOREIGN KEY (anulada_por) REFERENCES auth_users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE movimientos (
  id BIGINT NOT NULL AUTO_INCREMENT,
  status TINYINT NOT NULL DEFAULT 0,
  uuid CHAR(36) NOT NULL,
  id_user_created BIGINT NULL,
  id_user_updated BIGINT NULL,
  id_user_deleted BIGINT NULL,
  date_created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  date_updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  date_deleted TIMESTAMP NULL,
  company_id BIGINT NOT NULL,
  tipo VARCHAR(20) NOT NULL,
  monto DECIMAL(12, 2) NOT NULL,
  fecha DATE NOT NULL,
  medio_pago VARCHAR(30) NULL,
  cuota_id BIGINT NULL,
  persona_id BIGINT NULL,
  titular_id BIGINT NULL,
  concepto VARCHAR(255) NOT NULL,
  registrado_por BIGINT NOT NULL,
  observaciones TEXT NULL,
  estado VARCHAR(20) NOT NULL,
  anulada_por BIGINT NULL,
  anulada_motivo VARCHAR(512) NULL,
  anulada_at TIMESTAMP NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_movimientos_uuid (uuid),
  UNIQUE KEY uk_movimientos_ingreso_cuota (cuota_id),
  KEY fk_movimientos_company (company_id),
  KEY idx_movimientos_fecha (company_id, fecha),
  KEY idx_movimientos_tipo_estado (company_id, tipo, estado),
  KEY idx_movimientos_titular (company_id, titular_id),
  KEY fk_movimientos_registrado_por (registrado_por),
  KEY fk_movimientos_anulada_por (anulada_por),
  CONSTRAINT fk_movimientos_company FOREIGN KEY (company_id) REFERENCES companies (id),
  CONSTRAINT fk_movimientos_cuota FOREIGN KEY (cuota_id) REFERENCES cuotas (id),
  CONSTRAINT fk_movimientos_registrado_por FOREIGN KEY (registrado_por) REFERENCES auth_users (id),
  CONSTRAINT fk_movimientos_anulada_por FOREIGN KEY (anulada_por) REFERENCES auth_users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
