  date_updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  date_deleted TIMESTAMP NULL,
  torneo_id BIGINT NOT NULL,
  equipo_id BIGINT NULL,
  nombre VARCHAR(120) NOT NULL,
  PRIMARY KEY (id),
